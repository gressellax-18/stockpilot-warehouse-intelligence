export function getProductImage(sku?: string, fallbackUrl?: string): string {
  if (fallbackUrl && fallbackUrl.startsWith('http')) return fallbackUrl;
  if (!sku) return 'https://images.unsplash.com/photo-1610030469983-98e550d6193c?w=500&auto=format&fit=crop&q=80';
  return SKU_IMAGE_MAP[sku] || 'https://images.unsplash.com/photo-1610030469983-98e550d6193c?w=500&auto=format&fit=crop&q=80';
}

export function getWarehouseImage(whIdOrCode?: string): string {
  if (!whIdOrCode) return WAREHOUSE_IMAGE_MAP['wh-hyd'];
  const cleanKey = whIdOrCode.toLowerCase();
  if (cleanKey.includes('hyd')) return WAREHOUSE_IMAGE_MAP['wh-hyd'];
  if (cleanKey.includes('blr') || cleanKey.includes('bangalore') || cleanKey.includes('bengaluru')) return WAREHOUSE_IMAGE_MAP['wh-blr'];
  if (cleanKey.includes('che') || cleanKey.includes('maa') || cleanKey.includes('chennai')) return WAREHOUSE_IMAGE_MAP['wh-che'];
  if (cleanKey.includes('pun') || cleanKey.includes('pnq') || cleanKey.includes('pune')) return WAREHOUSE_IMAGE_MAP['wh-pun'];
  if (cleanKey.includes('del') || cleanKey.includes('ncr') || cleanKey.includes('delhi')) return WAREHOUSE_IMAGE_MAP['wh-del'];
  if (cleanKey.includes('kol') || cleanKey.includes('ccu') || cleanKey.includes('kolkata')) return WAREHOUSE_IMAGE_MAP['wh-kol'];
  return WAREHOUSE_IMAGE_MAP[whIdOrCode] || WAREHOUSE_IMAGE_MAP['wh-hyd'];
}
